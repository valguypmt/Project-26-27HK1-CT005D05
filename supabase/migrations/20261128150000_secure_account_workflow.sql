create or replace function public.require_verified_student_email()
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text;
begin
  if auth.uid() is null then
    raise exception 'Email verification is required.' using errcode = '28000';
  end if;

  select lower(btrim(u.email))
    into v_email
  from auth.users as u
  where u.id = auth.uid()
    and u.email_confirmed_at is not null;

  if v_email is null or v_email !~ '^[^[:space:]@]+@student\.ctu\.edu\.vn$' then
    raise exception 'A verified @student.ctu.edu.vn email is required.' using errcode = '42501';
  end if;

  return v_email;
end;
$$;

create or replace function public.require_moderator()
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null
    or coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'moderator' then
    raise exception 'Moderator access is required.' using errcode = '42501';
  end if;

  return auth.uid();
end;
$$;

create or replace function public.require_moderator_email_otp()
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_claims jsonb := auth.jwt();
  v_has_email_otp boolean;
begin
  perform public.require_moderator();

  select exists (
    select 1
    from jsonb_array_elements(coalesce(v_claims -> 'amr', '[]'::jsonb)) as methods(method)
    where methods.method ->> 'method' = 'otp'
  ) into v_has_email_otp;

  if coalesce(v_claims ->> 'aal', '') <> 'aal1' or not v_has_email_otp then
    raise exception 'Moderator email OTP verification is required.' using errcode = '42501';
  end if;

end;
$$;

create or replace function public.get_my_registration_status()
returns table(email text, account_name text, status text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := public.require_verified_student_email();
begin
  return query
  select u.email::text, u.account_name::text, u.status::text
  from public.users as u
  where lower(btrim(u.email)) = v_email;
end;
$$;

create or replace function public.submit_registration_request(p_account_name text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := public.require_verified_student_email();
  v_account_name text := btrim(coalesce(p_account_name, ''));
begin
  if v_account_name !~ '^[A-Za-z0-9_]{3,16}$' then
    raise exception 'Account name must be 3 to 16 letters, numbers, or underscores.'
      using errcode = '22023';
  end if;

  insert into public.users (email, account_name, status)
  values (v_email, v_account_name, 'pending');
end;
$$;

