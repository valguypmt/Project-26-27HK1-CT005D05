create or replace function public.submit_my_feedback(p_subject text, p_message text)
returns table(
  id bigint,
  subject text,
  message text,
  status text,
  moderator_reply text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := public.require_verified_student_email();
  v_subject text := btrim(coalesce(p_subject, ''));
  v_message text := btrim(coalesce(p_message, ''));
begin
  if v_subject not in ('password', 'username', 'account', 'other') then
    raise exception 'Feedback subject is invalid.' using errcode = '22023';
  end if;
  if v_message = '' or length(v_message) > 200 then
    raise exception 'Feedback message must contain 1 to 200 characters.' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(auth.uid()::text, 0)
  );
  if (select count(*) from public.feedback as f where f.user_id = auth.uid()) >= 3 then
    raise exception 'Feedback limit reached.' using errcode = '22023';
  end if;

  return query
  insert into public.feedback as f (user_id, email, subject, message, status)
  values (auth.uid(), v_email, v_subject, v_message, 'submitted')
  returning f.id, f.subject, f.message, f.status, f.moderator_reply, f.created_at;
end;
$$;

