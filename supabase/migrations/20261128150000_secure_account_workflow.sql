do $$
begin
  if exists (
    select lower(btrim(email))
    from public.users
    group by lower(btrim(email))
    having count(*) > 1
  ) then
    raise exception 'Duplicate normalized emails exist in public.users; resolve them before applying this migration.';
  end if;

  if exists (
    select lower(btrim(account_name))
    from public.users
    where account_name is not null
    group by lower(btrim(account_name))
    having count(*) > 1
  ) then
    raise exception 'Duplicate normalized account names exist in public.users; resolve them before applying this migration.';
  end if;
end
$$;

