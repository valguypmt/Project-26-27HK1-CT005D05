create or replace function public.claim_moderator_session(p_session_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_moderator_id uuid := public.require_moderator();
begin
  insert into public.moderator_session_locks (moderator_id, session_id, last_heartbeat)
  values (v_moderator_id, p_session_id, clock_timestamp())
  on conflict (moderator_id) do update
    set session_id = excluded.session_id,
        last_heartbeat = excluded.last_heartbeat
    where public.moderator_session_locks.session_id = excluded.session_id
       or public.moderator_session_locks.last_heartbeat < clock_timestamp() - interval '5 seconds';

  return found;
end;
$$;

create or replace function public.renew_moderator_session(p_session_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_moderator_id uuid := public.require_moderator();
begin
  update public.moderator_session_locks
  set last_heartbeat = clock_timestamp()
  where moderator_id = v_moderator_id
    and session_id = p_session_id;

  return found;
end;
$$;

create or replace function public.release_moderator_session(p_session_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_moderator_id uuid := public.require_moderator();
begin
  delete from public.moderator_session_locks
  where moderator_id = v_moderator_id and session_id = p_session_id;

  return found;
end;
$$;

