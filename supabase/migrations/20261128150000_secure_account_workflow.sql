create or replace function public.update_feedback_for_moderator(
  p_feedback_id bigint,
  p_status text,
  p_moderator_reply text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reply text := nullif(btrim(coalesce(p_moderator_reply, '')), '');
begin
  perform public.require_moderator_email_otp();
  if coalesce(p_status, '') not in ('in_progress', 'resolved', 'cancelled') then
    raise exception 'Feedback status is invalid.' using errcode = '22023';
  end if;
  if v_reply is not null and length(v_reply) > 200 then
    raise exception 'Moderator reply cannot exceed 200 characters.' using errcode = '22023';
  end if;

  update public.feedback
  set status = p_status,
      moderator_reply = v_reply,
      moderator_reply_by = case
        when v_reply is null then null
        else nullif(split_part(lower(coalesce(auth.jwt() ->> 'email', '')), '@', 1), '')
      end,
      updated_at = now()
  where id = p_feedback_id;

  if not found then
    raise exception 'Feedback item not found.' using errcode = 'P0002';
  end if;
  return true;
end;
$$;

