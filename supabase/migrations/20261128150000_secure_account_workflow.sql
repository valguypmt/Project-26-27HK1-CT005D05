create or replace function public.create_managed_user(
  p_email text,
  p_account_name text,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_account_name text := btrim(coalesce(p_account_name, ''));
begin
  perform public.require_moderator_email_otp();
  if v_email !~ '^[^[:space:]@]+@student\.ctu\.edu\.vn$' then
    raise exception 'A valid @student.ctu.edu.vn email is required.' using errcode = '22023';
  end if;
  if v_account_name !~ '^[A-Za-z0-9_]{3,16}$' then
    raise exception 'Account name must be 3 to 16 letters, numbers, or underscores.' using errcode = '22023';
  end if;
  if coalesce(p_status, '') not in ('pending', 'verified', 'banned') then
    raise exception 'Account status is invalid.' using errcode = '22023';
  end if;

  insert into public.users (email, account_name, status)
  values (v_email, v_account_name, p_status);
end;
$$;

